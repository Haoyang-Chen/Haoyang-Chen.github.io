(() => {
  const guide = document.getElementById('guided-demo');
  const steps = [...guide.querySelectorAll('[data-step]')];
  const stories = [...guide.querySelectorAll('[data-story]')];
  const frame = document.getElementById('guide-viewport');
  const camera = document.getElementById('guide-camera');
  const spotlight = document.getElementById('guide-spotlight');
  const previous = document.getElementById('guide-back');
  const next = document.getElementById('guide-next');
  let current = 0;

  // Regions use Figure 5's original pixel coordinates. Only the camera changes;
  // no rules, values, or model results are generated by this guided tour.
  const scenes = [
    { view: [180, 100, 720, 535], mobile: [200, 165, 510, 310], focus: [205, 150, 495, 325], next: 'Explore assistance' },
    { view: [640, 20, 520, 390], mobile: [690, 35, 430, 290], focus: [715, 55, 175, 165], next: 'Set the boundaries' },
    { view: [810, 20, 400, 380], mobile: [875, 35, 295, 280], focus: [905, 58, 225, 200], next: 'Compare the proposal' },
    { view: [1137, 95, 670, 495], mobile: [1140, 115, 665, 430], focus: [1145, 120, 655, 400], next: 'Replay the tour' }
  ];

  function updateCamera() {
    if (!frame.clientWidth) return;
    const scene = scenes[current];
    const [x, y, width, height] = frame.clientWidth < 550 ? scene.mobile : scene.view;
    const base = frame.clientWidth / 1820;
    const scale = Math.min(frame.clientWidth / (width * base), frame.clientHeight / (height * base)) * 0.94;
    const translateX = frame.clientWidth / 2 - (x + width / 2) * base * scale;
    const translateY = frame.clientHeight / 2 - (y + height / 2) * base * scale;
    camera.style.transform = `translate(${translateX}px, ${translateY}px) scale(${scale})`;
    const [left, top, focusWidth, focusHeight] = scene.focus;
    Object.assign(spotlight.style, {
      left: `${left / 1820 * 100}%`, top: `${top / 704 * 100}%`,
      width: `${focusWidth / 1820 * 100}%`, height: `${focusHeight / 704 * 100}%`
    });
  }

  function showStep(index, reveal = false) {
    current = Math.max(0, Math.min(index, scenes.length - 1));
    steps.forEach((button, i) => {
      if (i === current) button.setAttribute('aria-current', 'step');
      else button.removeAttribute('aria-current');
      stories[i].hidden = i !== current;
    });
    previous.disabled = current === 0;
    next.textContent = scenes[current].next;
    document.getElementById('guide-progress').textContent = `${current + 1} of ${scenes.length}`;
    updateCamera();
    if (reveal && guide.getBoundingClientRect().top < 90) guide.scrollIntoView({ block: 'start' });
  }

  steps.forEach((button, index) => {
    button.addEventListener('click', () => showStep(index, true));
    button.addEventListener('keydown', event => {
      const destination = {
        ArrowRight: (index + 1) % steps.length,
        ArrowLeft: (index + steps.length - 1) % steps.length,
        Home: 0,
        End: steps.length - 1
      }[event.key];
      if (destination === undefined) return;
      event.preventDefault();
      showStep(destination, true);
      steps[destination].focus({ preventScroll: true });
    });
  });
  previous.addEventListener('click', () => showStep(current - 1, true));
  next.addEventListener('click', () => showStep(current === steps.length - 1 ? 0 : current + 1, true));

  const dialog = document.getElementById('figure-dialog');
  const zoomButton = document.getElementById('zoom-figure');
  const enlarged = document.getElementById('dialog-image');
  let figureTrigger;
  zoomButton.addEventListener('click', () => {
    const zoomed = dialog.classList.toggle('is-zoomed');
    zoomButton.setAttribute('aria-pressed', String(zoomed));
    zoomButton.textContent = zoomed ? 'Fit image' : 'Zoom in';
  });
  document.querySelectorAll('[data-zoom]').forEach(button => {
    button.addEventListener('click', () => {
      figureTrigger = button;
      const source = button.dataset.zoomImage ? document.getElementById(button.dataset.zoomImage) : button.querySelector('img');
      enlarged.src = source.src;
      enlarged.alt = source.alt;
      document.getElementById('dialog-caption').textContent = button.closest('figure').querySelector('figcaption').textContent;
      dialog.classList.remove('is-zoomed');
      zoomButton.setAttribute('aria-pressed', 'false');
      zoomButton.textContent = 'Zoom in';
      dialog.showModal();
      dialog.querySelector('.dialog-image-wrap').scrollTo(0, 0);
    });
  });
  document.getElementById('close-figure').addEventListener('click', () => dialog.close());
  dialog.addEventListener('click', event => { if (event.target === dialog) dialog.close(); });
  dialog.addEventListener('close', () => figureTrigger?.focus({ preventScroll: true }));

  document.getElementById('copy-citation').addEventListener('click', async () => {
    const status = document.getElementById('copy-status');
    try {
      await navigator.clipboard.writeText(document.getElementById('bibtex').textContent);
      status.textContent = 'Copied';
    } catch {
      status.textContent = 'Select the citation below to copy it.';
      document.querySelector('.citation pre').focus();
    }
  });

  document.documentElement.classList.add('has-js');
  document.querySelectorAll('[data-enhanced]').forEach(element => { element.hidden = false; });
  showStep(0);
  new ResizeObserver(updateCamera).observe(frame);
})();
